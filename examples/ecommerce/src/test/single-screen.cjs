const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const crypto = require('node:crypto')

const url = process.env.QA_URL || 'http://127.0.0.1:4173/'
const output = 'docs/evidence/single-screen'
async function main() {
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch()
  const results = []
  try {
    for (const [width, height] of [[2560, 1440], [1920, 1080], [1366, 768]]) {
      const context = await browser.newContext({ viewport: { width, height }, serviceWorkers: 'block', colorScheme: 'light' })
      const external = [], errors = [], requests = []
      await context.route('**/*', route => {
        if (new URL(route.request().url()).origin !== new URL(url).origin) { external.push(route.request().url()); return route.abort() }
        return route.continue()
      })
      const page = await context.newPage()
      page.on('pageerror', error => errors.push(error.message))
      page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
      page.on('response', response => requests.push({ url: response.url(), status: response.status() }))
      const button = name => page.getByRole('button', { name, exact: true })
      const map = async name => { await page.getByRole('img', { name: `${name}行政区地图`, exact: true }).locator('svg path').first().waitFor(); await page.waitForTimeout(120) }
      const area = code => page.getByLabel('选择下钻区域').selectOption(code)
      async function layout() {
        await page.waitForTimeout(200)
        const state = await page.evaluate(() => ({ width: innerWidth, height: innerHeight, scrollWidth: document.documentElement.scrollWidth, scrollHeight: document.documentElement.scrollHeight, panels: [...document.querySelectorAll('[data-slot="card"], footer, .toolbar')].map(el => { const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, right: r.right, bottom: r.bottom, overflow: el.scrollHeight - el.clientHeight } }), charts: [...document.querySelectorAll('[_echarts_instance_]')].map(el => ({ width: el.clientWidth, height: el.clientHeight, svgWidth: Number(el.querySelector('svg').getAttribute('width')), svgHeight: Number(el.querySelector('svg').getAttribute('height')) })) }))
        assert.equal(state.width, state.scrollWidth)
        assert.equal(state.height, state.scrollHeight)
        for (const panel of state.panels) assert.ok(panel.x >= 0 && panel.y >= 0 && panel.right <= width + 1 && panel.bottom <= height + 1 && panel.overflow <= 2, JSON.stringify(panel))
        assert.equal(state.charts.length, 5)
        for (const chart of state.charts) assert.ok(chart.height > 50 && Math.abs(chart.width - chart.svgWidth) < 2 && Math.abs(chart.height - chart.svgHeight) < 2, JSON.stringify(chart))
        return state
      }
      await page.goto(url)
      await map('全国')
      assert.equal(await page.getByRole('navigation', { name: '专题导航' }).count(), 0)
      const initial = await page.getByRole('region', { name: '核心指标' }).innerText()
      const geometry = await layout()
      const colors = await page.getByRole('img', { name: '全国行政区地图', exact: true }).locator('svg path').evaluateAll(paths => [...new Set(paths.map(path => path.getAttribute('fill')).filter(fill => fill && fill !== 'none'))])
      assert.ok(colors.length > 5)
      await page.screenshot({ path: `${output}/${width}x${height}-national.png` })
      await page.getByRole('img', { name: '全国行政区地图', exact: true }).locator('svg path').first().click()
      await map('北京市')
      await button('返回上级').click()
      await map('全国')
      await area('110000')
      await map('北京市')
      await button('返回上级').focus()
      await page.keyboard.press('Enter')
      await map('全国')
      await area('440000'); await map('广东省')
      assert.notEqual(await page.getByRole('region', { name: '核心指标' }).innerText(), initial)
      await area('440300'); await map('深圳市')
      await area('440305'); await map('南山区')
      await layout()
      await page.screenshot({ path: `${output}/${width}x${height}-district.png` })
      await button('返回上级').click(); await map('深圳市')
      await button('返回上级').click(); await map('广东省')
      await area('441900'); await map('东莞市')
      await page.getByText('来源未提供下级边界', { exact: true }).waitFor()
      assert.ok(await page.getByLabel('选择下钻区域').isDisabled())
      await button('全国').click(); await map('全国')
      assert.equal(await page.getByRole('region', { name: '核心指标' }).innerText(), initial)
      await page.getByLabel('开始日期').fill('2026-10-10')
      assert.notEqual(await page.getByRole('region', { name: '核心指标' }).innerText(), initial)
      await page.getByLabel('开始日期').fill('2027-01-01')
      await page.getByRole('alert').waitFor(); await layout()
      await button('重置筛选').click()
      assert.equal(await page.getByRole('region', { name: '核心指标' }).innerText(), initial)
      await button('进入全屏').click()
      await button('退出全屏').waitFor()
      await button('退出全屏').click()
      await button('进入全屏').waitFor()
      await button('切换为暗色主题').click()
      await layout()
      await page.screenshot({ path: `${output}/${width}x${height}-dark.png` })
      await page.reload(); await map('全国')
      assert.equal(await page.locator('html').getAttribute('class'), 'dark')
      await layout()
      assert.deepEqual(errors, []); assert.deepEqual(external, [])
      results.push({ width, height, geometry, colors: colors.length, errors, external, requests })
      await context.close()
    }
    const context = await browser.newContext({ viewport: { width: 1366, height: 768 } })
    const page = await context.newPage()
    const map = name => page.getByRole('img', { name: `${name}行政区地图`, exact: true }).waitFor()
    const area = code => page.getByLabel('选择下钻区域').selectOption(code)
    await page.goto(url); await map('全国')
    const initial = await page.getByRole('region', { name: '核心指标' }).innerText()
    await page.route('**/maps/440000_full.json', route => route.fulfill({ status: 404, body: 'missing' }))
    await area('440000'); await page.getByRole('alert').waitFor(); await map('全国')
    assert.equal(await page.getByRole('region', { name: '核心指标' }).innerText(), initial)
    await page.screenshot({ path: `${output}/missing-preserved.png` })
    await page.unroute('**/maps/440000_full.json')
    await page.getByRole('button', { name: '重试', exact: true }).click(); await map('广东省')
    await page.screenshot({ path: `${output}/recovered.png` })
    await page.getByRole('button', { name: '全国', exact: true }).click(); await map('全国')
    await page.route('**/maps/440000_full.json', route => route.fulfill({ status: 200, contentType: 'application/json', body: '{"type":"FeatureCollection","features":[]}' }))
    await area('440000'); await page.getByRole('alert').waitFor(); await map('全国')
    await page.unroute('**/maps/440000_full.json')
    await page.getByRole('button', { name: '继续查看原层', exact: true }).click()
    await page.getByRole('alert').waitFor({ state: 'hidden' })
    let release
    const gate = new Promise(resolve => { release = resolve })
    await page.route('**/maps/440000_full.json', async route => { await gate; await route.continue() })
    await area('440000'); await page.getByRole('button', { name: '取消加载', exact: true }).click()
    release(); await page.waitForTimeout(300); await map('全国')
    await page.unroute('**/maps/440000_full.json')
    let releaseSecond
    const secondGate = new Promise(resolve => { releaseSecond = resolve })
    await page.route('**/maps/440000_full.json', async route => { await secondGate; await route.continue() })
    await area('440000'); await area('330000'); await map('浙江省')
    releaseSecond(); await page.waitForTimeout(300); await map('浙江省')
    await context.close()
    const hash = crypto.createHash('sha256').update(await fs.readFile('dist/index.html')).digest('hex')
    await fs.writeFile(`${output}/results.json`, JSON.stringify({ timestamp: new Date().toISOString(), browser: browser.version(), distIndexSha256: hash, results, missingRecovery: true, corruptRecovery: true, cancelledRequest: true, rapidSwitch: true, fullscreen: true, keyboard: true, network: '全新会话阻断外网，保留本地生产服务器' }, null, 2))
    console.log(JSON.stringify({ browser: browser.version(), viewports: results.map(({ width, height }) => [width, height]), recovery: true, fullscreen: true }))
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
