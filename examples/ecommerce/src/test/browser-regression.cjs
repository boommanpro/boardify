const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const crypto = require('node:crypto')

const url = process.env.QA_URL || 'http://127.0.0.1:4173/'
const output = 'docs/evidence'
async function main() {
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch()
  const results = []
  try {
    for (const width of [1440, 1280, 390, 320]) {
      const context = await browser.newContext({ viewport: { width, height: 1000 }, serviceWorkers: 'block', colorScheme: 'light' })
      const external = []
      const requests = []
      await context.route('**/*', route => {
        const request = route.request().url()
        if (new URL(request).origin !== new URL(url).origin) { external.push(request); return route.abort() }
        return route.continue()
      })
      const page = await context.newPage()
      const errors = []
      page.on('pageerror', error => errors.push(error.message))
      page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
      page.on('response', response => requests.push({ url: response.url(), status: response.status() }))
      const button = name => page.getByRole('button', { name, exact: true })
      const topic = name => page.getByRole('navigation', { name: '专题导航' }).getByRole('button', { name })
      const area = name => page.locator('.region-list').getByRole('button', { name: new RegExp(name) })
      async function map(name) { await page.getByRole('img', { name: `${name}行政区地图`, exact: true }).locator('svg path').first().waitFor() }
      async function layout() {
        const state = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth, charts: [...document.querySelectorAll('[_echarts_instance_]')].map(el => ({ width: el.clientWidth, svg: Number(el.querySelector('svg').getAttribute('width')) })) }))
        assert.equal(state.viewport, state.document, JSON.stringify(state))
        for (const chart of state.charts) assert.ok(chart.width > 0 && Math.abs(chart.width - chart.svg) < 2)
      }
      await page.goto(url)
      await page.getByRole('heading', { name: '经营总览' }).waitFor()
      await page.getByRole('img', { name: '每日经营趋势' }).locator('svg').waitFor()
      await layout()
      const initial = await page.getByRole('region', { name: '核心指标' }).innerText()
      await page.getByLabel('渠道', { exact: true }).selectOption('自然搜索')
      assert.notEqual(await page.getByRole('region', { name: '核心指标' }).innerText(), initial)
      for (const name of ['流量', '商品', '用户', '履约']) {
        await topic(name).click()
        await page.getByRole('heading', { name: `${name}分析` }).waitFor()
        assert.equal(await page.getByLabel('渠道', { exact: true }).inputValue(), '自然搜索')
        await layout()
      }
      await page.getByLabel('开始日期').fill('2027-01-01')
      await page.getByText('当前筛选暂无模拟数据，请调整日期或重置筛选。').waitFor()
      await button('重置筛选').click()
      await topic('总览').click()
      assert.equal(await page.getByRole('region', { name: '核心指标' }).innerText(), initial)
      await page.screenshot({ path: `${output}/${width}-overview.png`, fullPage: true })
      await topic('地域').click()
      await map('全国')
      const colors = await page.getByRole('img', { name: '全国行政区地图', exact: true }).locator('svg path').evaluateAll(paths => [...new Set(paths.map(path => path.getAttribute('fill')).filter(fill => fill && fill !== 'none'))])
      assert.ok(colors.length > 5, `地图必须按业务数据着色：${colors}`)
      await page.screenshot({ path: `${output}/${width}-national.png`, fullPage: true })
      await page.getByRole('img', { name: '全国行政区地图', exact: true }).locator('svg path').first().click()
      await map('北京市')
      await page.getByRole('navigation', { name: '地图路径' }).getByRole('button', { name: '全国', exact: true }).click()
      await map('全国')
      await area('广东省').focus()
      await page.keyboard.press('Enter')
      await map('广东省')
      await area('深圳市').click()
      await map('深圳市')
      await area('南山区').click()
      await map('南山区')
      await page.getByText('区县边界为最细层级，不含乡镇', { exact: true }).waitFor()
      await button('切换为暗色主题').click()
      await layout()
      await page.screenshot({ path: `${output}/${width}-district-dark.png`, fullPage: true })
      await button('返回上级').click()
      await map('深圳市')
      await button('返回上级').click()
      await map('广东省')
      await area('东莞市').click()
      await map('东莞市')
      await page.getByText('来源未提供下级边界', { exact: true }).waitFor()
      await page.getByRole('navigation', { name: '地图路径' }).getByRole('button', { name: '全国', exact: true }).click()
      await map('全国')
      await area('北京市').click()
      await map('北京市')
      await area('东城区').click()
      await map('东城区')
      await page.getByRole('navigation', { name: '地图路径' }).getByRole('button', { name: '全国', exact: true }).click()
      await map('全国')
      for (let index = 0; index < 10; index++) { await topic('总览').click(); await topic('地域').click(); await map('全国') }
      assert.equal(await page.locator('[_echarts_instance_]').count(), 1)
      await page.reload()
      assert.equal(await page.locator('html').getAttribute('class'), 'dark')
      await topic('地域').click()
      await map('全国')
      await layout()
      assert.deepEqual(errors, [])
      assert.deepEqual(external, [])
      assert.ok(requests.some(request => request.url.endsWith('/maps/440300_full.json') && request.status === 200))
      results.push({ width, errors, external, requests, checks: ['六专题', '共享筛选', '空数据', '重置', '键盘下钻', '全国广东深圳南山返回', '东莞缺下级', '直辖市下钻', '十次卸载重入', '暗色刷新', '无横向溢出', '外网阻断冷启动'] })
      await context.close()
    }
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
    const page = await context.newPage()
    await page.goto(url)
    await page.getByRole('navigation', { name: '专题导航' }).getByRole('button', { name: '地域' }).click()
    await page.getByRole('img', { name: '全国行政区地图', exact: true }).waitFor()
    await page.route('**/maps/440000_full.json', route => route.fulfill({ status: 404, body: 'missing' }))
    await page.locator('.region-list').getByRole('button', { name: /广东省/ }).click()
    await page.getByRole('alert').waitFor()
    assert.equal(await page.getByRole('img', { name: '全国行政区地图', exact: true }).count(), 1)
    await page.unroute('**/maps/440000_full.json')
    await page.getByRole('button', { name: '重试', exact: true }).click()
    await page.getByRole('img', { name: '广东省行政区地图', exact: true }).waitFor()
    await page.screenshot({ path: `${output}/recovery.png`, fullPage: true })
    await page.getByRole('navigation', { name: '地图路径' }).getByRole('button', { name: '全国', exact: true }).click()
    await page.getByRole('img', { name: '全国行政区地图', exact: true }).waitFor()
    await page.route('**/maps/440000_full.json', route => route.fulfill({ status: 200, contentType: 'application/json', body: '{"type":"FeatureCollection","features":[]}' }))
    await page.locator('.region-list').getByRole('button', { name: /广东省/ }).click()
    await page.getByRole('alert').waitFor()
    assert.equal(await page.getByRole('img', { name: '全国行政区地图', exact: true }).count(), 1)
    await page.unroute('**/maps/440000_full.json')
    await page.getByRole('button', { name: '继续查看原层', exact: true }).click()
    await page.getByRole('alert').waitFor({ state: 'hidden' })
    let release
    const gate = new Promise(resolve => { release = resolve })
    await page.route('**/maps/440000_full.json', async route => { await gate; await route.continue() })
    await page.locator('.region-list').getByRole('button', { name: /广东省/ }).click()
    await page.getByRole('button', { name: '取消加载', exact: true }).click()
    release()
    await page.getByRole('button', { name: '返回上级', exact: true }).waitFor()
    await page.waitForTimeout(300)
    assert.equal(await page.getByRole('img', { name: '全国行政区地图', exact: true }).count(), 1)
    await page.unroute('**/maps/440000_full.json')
    let releaseSecond
    const secondGate = new Promise(resolve => { releaseSecond = resolve })
    await page.route('**/maps/440000_full.json', async route => { await secondGate; await route.continue() })
    await page.locator('.region-list').getByRole('button', { name: /广东省/ }).click()
    await page.locator('.region-list').getByRole('button', { name: /浙江省/ }).click()
    await page.getByRole('img', { name: '浙江省行政区地图', exact: true }).waitFor()
    releaseSecond()
    await page.waitForTimeout(300)
    assert.equal(await page.getByRole('img', { name: '浙江省行政区地图', exact: true }).count(), 1)
    await context.close()
    const hash = crypto.createHash('sha256').update(await fs.readFile('dist/index.html')).digest('hex')
    await fs.writeFile(`${output}/results.json`, JSON.stringify({ timestamp: new Date().toISOString(), browser: browser.version(), distIndexSha256: hash, network: '新会话阻断外网，保留本地服务', results, missingRecovery: true, corruptRecovery: true, cancelledRequest: true, rapidSwitch: true }, null, 2))
    console.log(JSON.stringify({ browser: browser.version(), viewports: results.map(result => result.width), checksPerViewport: results[0].checks.length, missingRecovery: true }))
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
